-- HANGTIME - estructura MySQL 8.x (opcional: la app también crea las tablas sola al arrancar)
CREATE DATABASE IF NOT EXISTS hangtime CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
USE hangtime;
SET FOREIGN_KEY_CHECKS = 0;
DROP TABLE IF EXISTS Items; DROP TABLE IF EXISTS Pedidos; DROP TABLE IF EXISTS Talles;
DROP TABLE IF EXISTS Productos; DROP TABLE IF EXISTS Usuarios;
SET FOREIGN_KEY_CHECKS = 1;

CREATE TABLE Usuarios (
  Id INT NOT NULL AUTO_INCREMENT, Nombre VARCHAR(100) NOT NULL, Email VARCHAR(160) NOT NULL,
  PasswordHash VARCHAR(100) NOT NULL, Rol VARCHAR(20) NOT NULL DEFAULT 'Cliente',
  CreadoEn DATETIME(6) NOT NULL, IntentosFallidos INT NOT NULL DEFAULT 0, BloqueadoHasta DATETIME(6) NULL,
  PRIMARY KEY (Id), UNIQUE KEY UX_Usuarios_Email (Email)) ENGINE=InnoDB;

CREATE TABLE Productos (
  Id INT NOT NULL AUTO_INCREMENT, Nombre VARCHAR(120) NOT NULL, Descripcion VARCHAR(500) NULL,
  Precio DECIMAL(10,2) NOT NULL, Categoria VARCHAR(30) NOT NULL,
  Color1 VARCHAR(7) NOT NULL, Color2 VARCHAR(7) NOT NULL, Color3 VARCHAR(7) NOT NULL,
  Destacado TINYINT(1) NOT NULL DEFAULT 0, Activo TINYINT(1) NOT NULL DEFAULT 1, CreadoEn DATETIME(6) NOT NULL,
  PRIMARY KEY (Id), INDEX IX_Productos_Categoria (Categoria)) ENGINE=InnoDB;

CREATE TABLE Talles (
  Id INT NOT NULL AUTO_INCREMENT, ProductoId INT NOT NULL, Numero INT NOT NULL, Stock INT NOT NULL,
  PRIMARY KEY (Id), UNIQUE KEY UX_Talles_Producto_Numero (ProductoId, Numero),
  CONSTRAINT FK_Talles_Productos FOREIGN KEY (ProductoId) REFERENCES Productos(Id) ON DELETE CASCADE) ENGINE=InnoDB;

CREATE TABLE Pedidos (
  Id INT NOT NULL AUTO_INCREMENT, UsuarioId INT NOT NULL, Direccion VARCHAR(250) NOT NULL,
  Estado VARCHAR(20) NOT NULL DEFAULT 'Pendiente', Total DECIMAL(12,2) NOT NULL, CreadoEn DATETIME(6) NOT NULL,
  PRIMARY KEY (Id),
  CONSTRAINT FK_Pedidos_Usuarios FOREIGN KEY (UsuarioId) REFERENCES Usuarios(Id) ON DELETE RESTRICT) ENGINE=InnoDB;

CREATE TABLE Items (
  Id INT NOT NULL AUTO_INCREMENT, PedidoId INT NOT NULL, TalleId INT NOT NULL,
  Cantidad INT NOT NULL, PrecioUnitario DECIMAL(10,2) NOT NULL,
  PRIMARY KEY (Id),
  CONSTRAINT FK_Items_Pedidos FOREIGN KEY (PedidoId) REFERENCES Pedidos(Id) ON DELETE CASCADE,
  CONSTRAINT FK_Items_Talles FOREIGN KEY (TalleId) REFERENCES Talles(Id) ON DELETE RESTRICT) ENGINE=InnoDB;
